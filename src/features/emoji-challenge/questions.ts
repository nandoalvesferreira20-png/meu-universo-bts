function questionsFor(
  difficulty: Difficulty,
  entries: readonly Entry[],
): EmojiQuestion[] {
  return entries.map(
    ([
      id,
      emojis,
      emojiDescription,
      explanation,
      source,
      distractors,
      optionalHint,
    ]) => ({
      id: `${difficulty}-${id}`,
      difficulty,
      emojis,
      emojiDescription,
      question: "Qual é a música?",
      correctAnswerId: id,
      explanation,
      optionalHint,
      sourceUrl: sources[source],
      options: [id, ...distractors].map((songId) => ({
        id: songId,
        title: songs[songId],
      })),
    }),
  );
}
export const emojiQuestions: readonly EmojiQuestion[] = [
  ...questionsFor("easy", easy),
  ...questionsFor("medium", medium),
  ...questionsFor("hard", hard),
];
