import type { CategoryId, QuizQuestion } from "./types";
import { quizSources } from "./sources";

// The correct answer is explicit. IDs derive from content, never shuffled position.
function answerId(title: string) {
  return `answer-${title
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}`;
}
function q(
  categoryId: CategoryId,
  id: string,
  question: string,
  correct: string,
  distractors: readonly [string, string, string],
  explanation: string,
  source: keyof typeof quizSources,
): QuizQuestion {
  return {
    id: `${categoryId}-${id}`,
    categoryId,
    question,
    correctAnswerId: answerId(correct),
    options: [correct, ...distractors].map((title) => ({
      id: answerId(title),
      title,
    })),
    explanation,
    sourceUrl: quizSources[source],
  };
}

